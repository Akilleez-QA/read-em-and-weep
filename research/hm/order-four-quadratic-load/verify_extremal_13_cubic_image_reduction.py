#!/usr/bin/env python3
"""Universal equivariant image bookkeeping for the (1,3) plateau."""
from pathlib import Path
from itertools import combinations_with_replacement
import contextlib,io,runpy
ROOT=Path(__file__).parent
with contextlib.redirect_stdout(io.StringIO()):
 r=runpy.run_path(str(ROOT/'verify_exceptional_cubic_gauss_corner.py'))
for key in ('va','vs','vm','sym','reps','zero','dimension','multiplicity','effective','hom','T','one','U','W','S'):
 globals()[key]=r[key]
def chi(e):return sym(e) if e>=0 else (zero if e==-1 else vs(-1,sym(-e-2)))
def cohom(B,t=0,dual=False,euler=False):
 return va(zero,*[vm(reps[n],chi(t-e if dual else t+e)) if euler else
 vm(reps[n],sym(t-e if dual else t+e)) for e,n in B if euler or (t-e if dual else t+e)>=0])
def deg(B):return sum(e*dimension(reps[n]) for e,n in B)
# Saturation of rank-three cubic image is generically generated by U.
# D>=11 and D-17<=h0(Sbar*(2))+h0(Sbar*)<=12, hence D<=29.
eligible=[]
for e in range(30):
 for n,R in reps.items():
  if dimension(R)>3 or R[1][0]!=(-1)**(e+1)*R[0][0]:continue
  if hom(U,vm(R,sym(e))):eligible.append((e,n))
survivors=[]
for count in range(1,4):
 for B in combinations_with_replacement(eligible,count):
  if sum(dimension(reps[n]) for e,n in B)!=3 or not 11<=deg(B)<=29:continue
  if not effective(va(cohom(B),vs(-1,U))):continue
  Kchi=va(T,vs(-2,W),vs(-1,S),vs(-1,cohom(B,4,True,True)))
  envelope=va(cohom(B,2,True),cohom(B,0,True))
  if effective(va(envelope,vs(-1,Kchi))):survivors.append(B)
assert survivors==[((0,'Wp'),(15,'one')),((0,'Wp'),(17,'one')),
                   ((0,'Wp'),(19,'one')),((2,'Wp'),(7,'one'))]
# U injects into H0(J); global generation gives deg J>=14-3=11.
# Both J and the full actual derivative image I lie between J and Sbar.
# Every possible defect is nonnegative and <12, hence is zero.
assert all(0<=deg(B)-11<12 for B in survivors)
assert [12*a+20*b+30*c for a in range(2) for b in range(2)
        for c in range(2) if 0<12*a+20*b+30*c<12]==[]
# Necessary individual Q* blocks, from BOTH actual positive Euler identities.
# j*dim R<=dim M3=54 makes this exhaustive. No realizability assumed.
qblocks=[]
for j in range(1,55):
 for n,R in reps.items():
  if R[1][0]!=(-1)**j*R[0][0]:continue
  c3=vm(R,sym(j-1));c2=vm(R,sym(j-2)) if j>=2 else zero
  if effective(va(r['M3'],vs(-1,c3))) and effective(va(r['M2'],vs(-1,c2))):qblocks.append((j,n))
assert [x for x in qblocks if x[0]>=14]==[(16,'one'),(17,'W'),(18,'one'),(28,'one')]
def line_targets(e):
 return [(j,n) for j,n in qblocks if j+1>=e and hom(one,vm(reps[n],sym(j+1-e)))]
assert line_targets(15)==[]
assert line_targets(17)==[(16,'one'),(17,'W'),(28,'one')]
assert line_targets(19)==[(18,'one')]
final=[B for B in survivors if all(any(j+1>=e and
 hom(reps[n],vm(reps[m],sym(j+1-e))) for j,m in qblocks) for e,n in B)]
assert final==[((0,'Wp'),(17,'one')),((0,'Wp'),(19,'one')),((2,'Wp'),(7,'one'))]
# In the degree-eleven case, H0(K(3))=0 forces K=14 O(-4).
# Its exact coefficient representation is obtained from E(4)-I(1).
E4=va(vm(U,W),reps['V'])
assert va(E4,vs(-1,cohom(((2,'Wp'),(7,'one')),1)))==va(vs(2,reps['V']),vs(2,reps['P']))
assert -54-(11-9)==-56 and -56+3*14==-14
print('PASS: (1,3) rank-three cubic image is saturated and equals the full derivative image.')
print('Exactly three necessary images remain: Wp O + O(17), Wp O + O(19), Wp O(2) + O(7).')
print('Degree-eleven case forces E^-=(2V+2P4) O(-4).')
