@lru_cache(None)
def partitions(n,r,minimum=0):
 if r==0:return ((),)if n==0 else ()
 return tuple((a,)+tail for a in range(minimum,n//r+1)for tail in partitions(n-a,r-1,a))
@lru_cache(None)
def reps(n,par,start=0):
 if n==0:return ((),)
 out=[]
 for i in range(start,9):
  if PAR[i]==par and DIMS[i]<=n:
   out.extend((i,)+tail for tail in reps(n-DIMS[i],par,i))
 return tuple(out)
@lru_cache(None)
def splitting(rank,degree,bound,lower=False):
 amount=degree-rank*bound if lower else rank*bound-degree
 if amount<0:return ()
 out=[]
 for ps in partitions(amount,rank):
  es=[bound+x if lower else bound-x for x in ps]
  grouped=sorted(Counter(es).items())
  for coeffs in product(*(reps(n,e%2)for e,n in grouped)):
   out.append(tuple((e,i)for (e,n),rr in zip(grouped,coeffs)for i in rr))
 check(len(out)==len(set(out)),'splitting duplicates')
 for bb in out:
  check(sum(DIMS[i]for e,i in bb)==rank,'splitting rank')
  check(sum(e*DIMS[i]for e,i in bb)==degree,'splitting degree')
 return tuple(sorted(out))

def sig(bs):return chi(bs,0)+chi(bs,1)
def sigsum(bs):return add(chi(bs,-2),chi(bs,0))+add(chi(bs,-1),chi(bs,1))
def hom(x,y):
 e,i=x;f,j=y
 return tensor_sym(j,f-e)[i]
def horizontal_witness(endpoint,target):
 live={i for i,x in enumerate(endpoint)if any(hom(x,y)>0 for y in target)}
 while True:
  more={i for i,x in enumerate(endpoint)if any(j in live and hom(x,(y[0]-2,y[1]))>0 for j,y in enumerate(endpoint))}
  if more<=live:break
  live|=more
 dead=tuple(i for i in range(len(endpoint))if i not in live)
 if dead:
  check(all(hom(endpoint[i],y)==0 for i in dead for y in target),'witness external Hom')
  check(all(hom(endpoint[i],(endpoint[j][0]-2,endpoint[j][1]))==0 for i in dead for j in live),'witness internal Hom')
 return dead

