#!/usr/bin/env python3
"""Coefficient-basis controls only. No physical HM source/polynomial evaluation."""
import sys

if not __debug__:
    print("ERROR: assertions are disabled; rerun without -O/-OO.", file=sys.stderr)
    raise SystemExit(2)

from itertools import product
from collections import Counter
from json import dumps

COUNTS = Counter()

def add(out, key, coeff):
    if coeff:
        out[key] = out.get(key, 0) + coeff
        if not out[key]:
            del out[key]

def linear(op, vector):
    out = {}
    for key, coeff in vector.items():
        for target, c in op(key).items():
            add(out, target, coeff*c)
    return out

def plus(*vectors):
    out = {}
    for vector in vectors:
        for key, coeff in vector.items():
            add(out, key, coeff)
    return out

def degree(key):
    return int(key[0] == 'C')

def basis(n):
    return [(s,e) for s in 'ABC' for e in range(-3,2)
            if s == 'C' or (s == 'A' and e >= 0) or (s == 'B' and e <= n)]

def d1(n, key):
    s,e=key
    return {('C',e): -1 if s == 'A' else 1} if s != 'C' else {}

def h1(n, key):
    s,e=key
    if s != 'C': return {}
    if e >= 0: return {('A',e):-1}
    if e <= n: return {('B',e):1}
    return {}

def ht1(n, key):
    """Independent transpose formula, not generated by reversing h1."""
    s,e=key
    if s == 'A' and e >= 0: return {('C',e):-1}
    if s == 'B' and e < 0 and e <= n: return {('C',e):1}
    return {}

def j1(n, key):
    s,e=key
    if n == 0 and key == ('B',0): return {('A',0):1, ('B',0):1}
    if n == -2 and key == ('C',-1): return {key:1}
    return {}

def jt1(n, key):
    if n == 0 and key in [('A',0),('B',0)]: return {('B',0):1}
    if n == -2 and key == ('C',-1): return {key:1}
    return {}

def tensor_term(ns, key, maps, sign=1):
    out = {():sign}
    for n,k,fn in zip(ns,key,maps):
        new = {}
        for prefix,c in out.items():
            for target,a in fn(n,k).items(): add(new,prefix+(target,),c*a)
        out = new
    return out

def identity(n,key): return {key:1}

def d(ns,key):
    out={}
    for j in range(len(ns)):
        maps=[identity]*len(ns);maps[j]=d1
        sign=(-1)**sum(map(degree,key[:j]))
        out=plus(out,tensor_term(ns,key,maps,sign))
    return out

def hom(ns,key,transpose=False):
    out={}
    for j in range(len(ns)):
        maps=[jt1 if transpose else j1]*j+[ht1 if transpose else h1]+[identity]*(len(ns)-j-1)
        sign=(-1)**sum(map(degree,key[:j]))
        out=plus(out,tensor_term(ns,key,maps,sign))
    return out

def proj(ns,key): return tensor_term(ns,key,[j1]*len(ns))

def check_adjoint(ns,key):
    # Two-way support/coefficient verification proves all matrix entries,
    # including absent zero entries, without a quadratic matrix enumeration.
    for target,coeff in hom(ns,key).items():
        assert hom(ns,target,True).get(key,0)==coeff,(ns,key,target,'forward')
        COUNTS['tensor_adjoint_forward_entries']+=1
    for source,coeff in hom(ns,key,True).items():
        assert hom(ns,source).get(key,0)==coeff,(ns,source,key,'reverse')
        COUNTS['tensor_adjoint_reverse_entries']+=1
    COUNTS['tensor_adjoint_basis_support_checks']+=1

def deriv1(key):
    state,exponent=key
    return {(state,exponent-1):exponent} if exponent else {}

def derivative_tensor(key,axis):
    state,exponent=key[axis]
    if not exponent:return {}
    target=list(key);target[axis]=(state,exponent-1)
    return {tuple(target):exponent}

def main():
    for n in (0,-2):
        for a in basis(n):
            for b in basis(n):
                assert h1(n,a).get(b,0)==ht1(n,b).get(a,0)
                COUNTS['one_factor_h_adjoint_pairings']+=1
                assert j1(n,a).get(b,0)==jt1(n,b).get(a,0)
                COUNTS['one_factor_J_adjoint_pairings']+=1
    for key in basis(0):
        assert linear(deriv1,h1(0,key))==linear(lambda x:h1(-2,x),deriv1(key))
        COUNTS['one_factor_derivative_h_commutation']+=1
        assert not linear(deriv1,j1(0,key))
        assert not linear(lambda x:j1(-2,x),deriv1(key))
        COUNTS['one_factor_derivative_J_zero_checks']+=2
    for factors in range(1,5):
        for ns in product((0,-2),repeat=factors):
            for key in product(*(basis(n) for n in ns)):
                actual=plus(linear(lambda x:d(ns,x),hom(ns,key)),linear(lambda x:hom(ns,x),d(ns,key)))
                expected=plus({key:1},{k:-v for k,v in proj(ns,key).items()})
                assert actual==expected,(ns,key,actual,expected)
                COUNTS['tensor_contraction_basis_identities']+=1
                assert not linear(lambda x:hom(ns,x),hom(ns,key))
                COUNTS['tensor_H_squared_zero']+=1
                assert not linear(lambda x:d(ns,x),d(ns,key))
                COUNTS['tensor_d_squared_zero']+=1
                check_adjoint(ns,key)
                for axis,n in enumerate(ns):
                    if n != 0:continue
                    target_ns=list(ns);target_ns[axis]=-2;target_ns=tuple(target_ns)
                    actual=linear(lambda x:derivative_tensor(x,axis),hom(ns,key))
                    expected=linear(lambda x:hom(target_ns,x),derivative_tensor(key,axis))
                    assert actual==expected,(ns,key,axis,'derivative tensor commutation')
                    COUNTS['tensor_derivative_h_commutation']+=1
    # [x^e](x^m partial_x^r f) = falling(e-m+r,r) [x^(e-m+r)]f.
    # Negative Laurent powers are included; multiplication is integer metadata.
    for exponent,requested,shift,order in product(range(-6,7),range(-4,5),range(-2,3),range(3)):
        falling=1
        for j in range(order):falling*=exponent-j
        lhs=falling if exponent-order+shift==requested else 0
        source=requested-shift+order
        weight=1
        for j in range(order):weight*=source-j
        rhs=weight if exponent==source else 0
        assert lhs==rhs
        COUNTS['Laurent_derivative_adjoint_pairings']+=1
    # Explicit controls reject common zero-mode and Koszul-sign mistakes.
    assert ht1(0,('B',0))=={}
    assert ht1(0,('A',0))=={('C',0):-1}
    assert jt1(0,('A',0))=={('B',0):1}
    assert jt1(0,('B',0))=={('B',0):1}
    assert ht1(-2,('B',-2))=={('C',-2):1}
    assert hom((-2,-2),(('C',-1),('C',-2)))=={(('C',-1),('B',-2)):-1}
    assert hom((-2,-2),(('C',-1),('B',-2)),True)=={(('C',-1),('C',-2)):-1}
    COUNTS['explicit_sign_and_zero_mode_controls']=7
    print(dumps({'status':'PASS','scope':'formal monomial bases only; no HM physical source arithmetic','counts':dict(sorted(COUNTS.items())),'total_recorded_checks':sum(COUNTS.values())},indent=2))

if __name__=='__main__':main()
