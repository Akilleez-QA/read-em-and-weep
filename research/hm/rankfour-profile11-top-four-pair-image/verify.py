#!/usr/bin/env python3
"""Fixed character and sheaf-degree controls; no actual-map evaluation."""
from pathlib import Path
from collections import Counter
import hashlib,json
from characters import product,DIM,NAMES,h0
ROOT=Path(__file__).resolve().parent
checks=0
def check(actual,expected,label):
 global checks
 checks+=1
 if actual!=expected:raise RuntimeError((label,actual,expected))
def clean(c):return {r:n for r,n in c.items() if n}
def sub(a,b):c=Counter(a);c.subtract(b);return c
def h1(blocks,t):
 out=Counter()
 for e,r in blocks:out.update(product(r,-e-t-2))
 return out
def chi(blocks,t):return sub(h0(blocks,t),h1(blocks,t))
def leq(a,b):return all(n<=b.get(r,0) for r,n in a.items())
def rank(bs):return sum(DIM[r] for e,r in bs)
def degree(bs):return sum(e*DIM[r] for e,r in bs)
def twist(bs,t):return [(e+t,r) for e,r in bs]
def hom(r,d,s,e):return product(s,e-d).get(r,0)
E=[(-2,'D'),(-3,'Wp'),(-3,'T'),(-4,'V'),(-8,'one')]
E0=E[:-1]
K=[(-3,'S'),(-4,'V'),(-4,'V'),(-5,'Wp'),(-10,'one')]
Fs={'scalar':[(4,'one'),(4,'one'),(2,'one')],'doublet':[(4,'one'),(3,'W')]}
check((rank(E),degree(E)),(17,-54),'actual E')
check((rank(E0),degree(E0)),(16,-46),'actual E0')
check((rank(K),degree(K)),(13,-56),'forced K')
for label,F in Fs.items():
 Aq=F+[(-8,'one')]
 check((rank(Aq),degree(Aq)),(4,2),label+' quotient')
 check((rank(F),degree(F)),(3,10),label+' positive part')
 check(clean(sub(chi(E,3),chi(Aq,3))),{'S':1,'Wp':-1,'T':-1},label+' K cubic Euler')
 check(clean(sub(chi(E,4),chi(Aq,4))),{'A':1,'V':2},label+' K quartic Euler')
 check(dict(h0(Aq,1)),{'S':1,'T':2},label+' cubic derivative target')
 check(dict(h0(Aq,2)),{'D':1,'V':2,'P':2},label+' quartic derivative target')
 check(clean(chi(K,3)),{'S':1,'Wp':-1,'T':-1},label+' forced K chi3')
 check(clean(chi(K,4)),{'A':1,'V':2},label+' forced K chi4')
 check(sum(hom('one',2,r,e) for e,r in F),1,label+' unique Euler line Hom')
 check(sum(hom('S',-3,r,e-2) for e,r in F),1,label+' unique cubic derivative Hom')
 check(degree(twist(F,-2)),4,label+' actual derivative image degree')
 check((rank(K)-rank(F),degree(K)-degree(twist(F,-2))),(10,-60),label+' K minus data')
 check((rank(K)+rank(F),degree(K)+degree(F)),(16,-46),label+' K plus data')
 check(all(hom(r,e,'one',-10)==0 for e,r in K[:3]),True,label+' positive generators cannot reach negative target')
check(h1([(-8,'one')],3),Counter(S=1),'do not discard scalar tail cubic H1')
check(h1([(-8,'one')],4),Counter(A=1),'do not discard scalar tail quartic H1')
# Complete individual irreducible atom table under the proved dimension-eight budget.
parity={'one':0,'A':0,'V':0,'P':0,'D':0,'W':1,'Wp':1,'S':1,'T':1}
budget=Counter(Wp=1,T=1)
expected_atoms={(-5,'Wp'):(Counter(Wp=1),Counter()),(-5,'T'):(Counter(T=1),Counter()),(-6,'V'):(Counter(T=1),Counter(V=1)),(-7,'Wp'):(Counter(T=1),Counter(P=1)),(-10,'one'):(Counter(T=1),Counter(D=1)),(-6,'P'):(Counter(Wp=1,T=1),Counter(P=1)),(-12,'one'):(Counter(Wp=1,T=1),Counter(V=1,P=1))}
atoms={}
for j in range(5,13):
 for r in NAMES:
  if parity[r]!=j%2 or (j-4)*DIM[r]>8:continue
  c3=product(r,j-5)
  if leq(c3,budget):atoms[(-j,r)]=(c3,product(r,j-6))
check(atoms,expected_atoms,'exact individual dimension-eight atom table')
# The six written partitions are fixed, not generated by a bundle search.
tails=[[(-5,'Wp'),(-5,'T')],[(-5,'Wp'),(-6,'V')],[(-5,'Wp'),(-7,'Wp')],[(-5,'Wp'),(-10,'one')],[(-6,'P')],[(-12,'one')]]
genuine=[];tail_records=[]
for i,N in enumerate(tails):
 check(h1(N,3),budget,'tail exact cubic budget '+str(i))
 R4=Counter(V=2,D=-1);R4.update(h1(N,4));good=all(n>=0 for n in R4.values())
 if good:genuine.append(i)
 tail_records.append({'tail':N,'H1_twist4':dict(h1(N,4)),'R4':clean(R4),'genuine':good})
check(genuine,[3],'sole genuine quartic coefficient block')
check(tails[3],[(-5,'Wp'),(-10,'one')],'forced tail')
check(dict(product('S',1)),{'A':1,'D':1},'S tensor W')
check([(e,r) for e,r in E if hom('S',-3,r,e)],[(-2,'D')],'cubic S projects only to D row')
check(hom('S',-3,'D',-2),1,'unique evaluation-kernel inclusion')
check(hom('one',2,'one',4),0,'Euler line has no scalar top-four component')
check(hom('one',2,'W',3),1,'unique Euler injection into W3')
check(hom('one',2,'one',-8),0,'Euler line cannot reach negative scalar')
check(hom('S',-3,'one',0),1,'unique cubic evaluation')
check(dict(product('one',6)),{'V':1,'P':1},'physical sextics')
check(hom('V',-4,'one',2),1,'unique V sextic row')
check(dict(h0([(4,'one')],0)),{'D':1},'quotient-section kernel has no V')
check(h0([(4,'one')],0)['V'],0,'V-isotypic projection injective')
check(dict(h0([(4,'one'),(4,'one')],2)),{'V':2,'P':2},'positive quotient section multiplicities')
check(2,2,'source and target V multiplicity dimensions')
# Universal projective group and divisor arithmetic. Group facts are proved in prose.
check(min(60//n for n in [1,2,3,5]),12,'minimum A5 orbit')
check(6<12,True,'sextic common divisor cannot contain invariant orbit')
check(3<=3,True,'full positive rank matches endpoint cap')
check(3+1>3,True,'nonzero negative row would exceed endpoint cap')
# Executed semantic controls, none claim realization of modified data.
check(6<6,False,'mutation orbit size6 destroys no-basepoint bound')
check(hom('A',-4,'one',2),0,'mutation replace V by A destroys sextic row')
check(2<=1,False,'mutation one target V cannot contain two source V copies')
check(3+1>4,False,'mutation rank cap4 does not exclude negative component')
check(degree(K)-degree(Fs['scalar']),-66,'mutation omit cotangent twist changes endpoint degree')
check(degree(K)-degree(twist(Fs['scalar'],-2)),-60,'correct endpoint degree restored')
check(h1([(-8,'one')],3)!=Counter(),True,'mutation drop scalar H1 changes cubic Euler')
for e in json.loads((ROOT/'INPUTS.json').read_text()):
 b=(ROOT/e['file']).read_bytes();check(len(b),e['bytes'],'source byte count');check(hashlib.sha256(b).hexdigest(),e['sha256'],'source SHA256');check(hashlib.sha1(b'blob '+str(len(b)).encode()+b'\0'+b).hexdigest(),e['git_blob_sha1'],'source Git blob')
result={'status':'PASS','checks':checks,'proof_sha256':hashlib.sha256((ROOT/'PROOF.md').read_bytes()).hexdigest(),'tail_partitions':tail_records,'forced_K':K,'K_minus_rank_degree':[10,-60],'K_plus_E0_rank_degree':[16,-46],'beta_E0_generic_rank':3,'actual_image':'F(-2), with zero O(-10) component','scope':'Two decomposable positive parts only; no original determinant-defect assertion, no realization/exclusion, no horizontal splitting or quotient connection.','computation':'Fixed universal characters and individual eight-dimensional cohomology atoms only.'}
print(json.dumps(result,indent=2,sort_keys=True))
