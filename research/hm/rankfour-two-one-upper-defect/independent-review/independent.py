def hom(x,y):
 e,i=x;f,j=y
 return tensor_sym(j,f-e)[i]
def horizontal_witness(endpoint,target):
 live={i for i,x in enumerate(endpoint)if any(hom(x,y)>0 for y in target)}
 while True:
  more={i for i,x in enumerate(endpoint)if any(j in live and hom(x,(y[0]-2,y[1]))>0 for j,y in enumerate(endpoint))}
  if more<=live:break
  live|=more
 dead=tuple(i for i in range(len(endpoint))if i not in live)
 if dead:
  check(all(hom(endpoint[i],y)==0 for i in dead for y in target),'witness external Hom')
  check(all(hom(endpoint[i],(endpoint[j][0]-2,endpoint[j][1]))==0 for i in dead for j in live),'witness internal Hom')
 return dead

@lru_cache(None)
def torsion_atom(n,r,t):return sub(linechi(0,r+t),linechi(0,r+t-n))
def torsion(desc,t):return add(*(torsion_atom(n,r,t)for n,r in desc))
def torsion_domains():
 # Independent enumeration by orbit multiplicity triple, then multisets
 # of local simple characters. Arbitrary nonreduced layers are retained.
 from itertools import combinations_with_replacement
 out={}
 for p,q,r in product(range(5),range(3),range(2)):
  weight=12*p+20*q+30*r
  if weight>54:continue
  for rr12,rr20,rr30 in product(combinations_with_replacement(range(0,10,2),p),combinations_with_replacement(range(0,6,2),q),combinations_with_replacement(range(0,4,2),r)):
   desc=tuple([(12,s)for s in rr12]+[(20,s)for s in rr20]+[(30,s)for s in rr30])
   signature=torsion(desc,0)+torsion(desc,1)
   out.setdefault(weight,{})[signature]=desc
 return out
def make_cases():
 sem=sorted({12*p+20*q+30*r for p,q,r in product(range(5),range(3),range(2))if 12*p+20*q+30*r<=54})
 cases=[];discard=[]
 for d1,d2 in product(sem,repeat=2):
  if d1+2*d2>54:continue
  for a in range(-82,-27,2):
   numerator=-138+d1+2*d2-a
   if numerator%2:continue
   b=numerator//2
   if b>-28 or b%2:continue
   c1=(-62-a-d1)//2
   if c1%2:continue
   d=c1+8+d1
   if d+28<max(-d,0)or 19-d-d2<0:
    discard.append((a,b,d1,d2,d));continue
   check(a+2*c1+8+d1==-54,'central degree')
   check(a+3*c1+24+2*d1+d2==b,'endpoint degree')
   cases.append((a,b,d1,d2,d))
 return sorted(cases),discard
