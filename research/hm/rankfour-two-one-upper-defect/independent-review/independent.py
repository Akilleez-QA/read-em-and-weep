@lru_cache(None)
def cheb(n,x):
 if n==0:return q(1)
 if n==1:return x
 return plus(mul(x,cheb(n-1,x)),scale(cheb(n-2,x),-1))
CH=[tuple(cheb(n,x)for x in TR)for n in range(6)]
