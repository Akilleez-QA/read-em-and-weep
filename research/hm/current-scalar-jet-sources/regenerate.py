#!/usr/bin/env python3
"""Regenerate pinned source circuits only; no rational quotient evaluation."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import platform
from pathlib import Path
import subprocess
import sys
import tempfile
import time

if sys.flags.optimize:
    raise RuntimeError('Run assertion-enabled Python, without -O')

HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--numerator', type=Path, required=True,
                        help='Pinned local-numerator.dag.json generated by current-scalar-numerator')
    parser.add_argument('--numerator-package', type=Path,
                        default=HERE.parent / 'current-scalar-numerator')
    parser.add_argument('--output-dir', type=Path,
                        help='New directory; omitted uses and cleans a temporary directory')
    parser.add_argument('--jobs', type=int, choices=(1, 2, 3, 4), default=1,
                        help='Independent axis processes (1 recommended for lower memory use)')
    parser.add_argument('--stage-timeout', type=int, default=120,
                        help='Seconds per leading or normalization stage')
    parser.add_argument('--axis-timeout', type=int, default=600,
                        help='Seconds per complete axis including all three compact/clearing pairs')
    parser.add_argument('--receipt', type=Path,
                        help='Optional fresh external path for the small verification receipt')
    args = parser.parse_args()
    numerator = args.numerator.resolve()
    ring = args.numerator_package.resolve() / 'tagged_ring.js'
    pins = json.loads((HERE / 'pins.json').read_text())
    if hashlib.sha256(numerator.read_bytes()).hexdigest() != pins['numeratorSHA256']:
        parser.error('Numerator does not match the completed current-L exact-Q pin')
    if not ring.is_file():
        parser.error('Missing tagged_ring.js in --numerator-package')
    ring_pin = json.loads((HERE / 'implementation-provenance.json').read_text())['taggedRing']['sha256']
    if hashlib.sha256(ring.read_bytes()).hexdigest() != ring_pin:
        parser.error('Exact tagged_ring.js dependency pin mismatch')
    if args.stage_timeout <= 0 or args.axis_timeout <= 0:
        parser.error('Timeouts must be positive')
    if args.receipt and args.receipt.exists():
        parser.error('Refuse to overwrite receipt')
    temp = None
    if args.output_dir:
        output = args.output_dir.resolve()
        output.mkdir(parents=True, exist_ok=False)
    else:
        temp = tempfile.TemporaryDirectory(prefix='current-L-jets-')
        output = Path(temp.name)
    started = time.monotonic()

    def axis_job(axis):
        with (output / f'axis-{axis}.log').open('x') as log:
            subprocess.run([sys.executable, str(HERE / 'build_axis.py'),
                            '--numerator', str(numerator), '--tagged-ring', str(ring),
                            '--output-dir', str(output), '--axis', str(axis),
                            '--stage-timeout', str(args.stage_timeout)],
                           stdout=log, stderr=subprocess.STDOUT,
                           check=True, timeout=args.axis_timeout)
        print(f'Axis {axis}: leading, normalization, support and three pairs match', flush=True)
        return json.loads((output / 'axes' / f'axis-{axis}.receipt.json').read_text())

    try:
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            results = list(pool.map(axis_job, range(4)))
        receipt = {'schema': 'current-L-rational-jet-regeneration-receipt-v1',
                   'status': 'ALL_32_EXACT_SOURCE_PINS_MATCH',
                   'numeratorSHA256': pins['numeratorSHA256'],
                   'pinsSHA256': hashlib.sha256((HERE / 'pins.json').read_bytes()).hexdigest(),
                   'pythonVersion': platform.python_version(),
                   'nodeVersion': subprocess.check_output(['node', '--version'], text=True).strip(),
                   'jobs': args.jobs, 'axes': results,
                   'elapsedSeconds': round(time.monotonic() - started, 3),
                   'polynomialQuotientEvaluationPerformed': False,
                   'geometricSourceProofPerformed': False}
        encoded = json.dumps(receipt, indent=2) + '\n'
        with (output / 'regeneration-receipt.json').open('x') as stream:
            stream.write(encoded)
        if args.receipt:
            with args.receipt.open('x') as stream:
                stream.write(encoded)
        print(json.dumps({'status': receipt['status'], 'elapsedSeconds': receipt['elapsedSeconds'],
                          'polynomialQuotientEvaluationPerformed': False}), flush=True)
    finally:
        if temp:
            temp.cleanup()


if __name__ == '__main__':
    main()
